def test_mixture_gradient_matches_finite_differences():
    """No symbolic branch sneaked in: autodiff agrees with central differences."""
    params = _params(use_hit_miss_mixture=True)
    valgrad = cefe.make_efe_valgrad_fn(
        params, _camera_H(), approx="ET1", p_vis_state=_p_vis_fixture()
    )
    u, m0, S0, goal_obs, goal_xy, prog = _EVAL_POINTS[0]
    u = np.asarray(u, dtype=float)
    args = (
        np.asarray(m0, dtype=float),
        np.asarray(S0, dtype=float),
        np.asarray(goal_obs, dtype=float),
        np.asarray(goal_xy, dtype=float),
        float(prog),
    )
    _, grad = valgrad(u, *args)
    h = 1e-6
    for i in range(u.size):
        up = u.copy()
        um = u.copy()
        up[i] += h
        um[i] -= h
        fd = (valgrad(up, *args)[0] - valgrad(um, *args)[0]) / (2.0 * h)
        assert fd == pytest.approx(grad[i], rel=2e-4, abs=2e-5)


def test_mixture_r_cond_defaults_to_r_visible_and_is_overridable():
    """R_cond default is documented as params.R_visible until a field is measured."""
    kwargs = dict(approx="ET1", p_vis_state=_p_vis_fixture())
    implicit = _evaluate_case(_params(use_hit_miss_mixture=True), kwargs)
    explicit = _evaluate_case(
        _params(use_hit_miss_mixture=True, R_cond=np.diag([2.5 ** 2, 2.5 ** 2])),
        kwargs,
    )
    for (va, ga), (vb, gb) in zip(implicit, explicit):
        assert va == vb
        assert ga == gb

    other = _evaluate_case(
        _params(use_hit_miss_mixture=True, R_cond=np.diag([9.0 ** 2, 6.0 ** 2])),
        kwargs,
    )
    assert any(a[0] != b[0] for a, b in zip(implicit, other))


