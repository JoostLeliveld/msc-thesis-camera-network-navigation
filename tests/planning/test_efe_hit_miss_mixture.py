def _golden_cases():
    """The (name, params, kwargs) configurations replayed by the golden test."""
    return (
        ("et1_vis", _params(), dict(approx="ET1", p_vis_state=_p_vis_fixture())),
        ("et2_vis", _params(), dict(approx="ET2", p_vis_state=_p_vis_fixture())),
        (
            "et1_vis_beliefnogo",
            _params(use_belief_nogo_cost=True),
            dict(
                approx="ET1",
                p_vis_state=_p_vis_fixture(),
                nogo_belief_cost=_nogo_belief_fixture(),
            ),
        ),
        ("et1_novis", _params(), dict(approx="ET1")),
    )


def _evaluate_case(params, kwargs):
    """Return [(objective, gradient_list), ...] over ``_EVAL_POINTS``."""
    valgrad = cefe.make_efe_valgrad_fn(params, _camera_H(), **kwargs)
    out = []
    for u, m0, S0, goal_obs, goal_xy, prog in _EVAL_POINTS:
        val, grad = valgrad(
            np.asarray(u, dtype=float),
            np.asarray(m0, dtype=float),
            np.asarray(S0, dtype=float),
            np.asarray(goal_obs, dtype=float),
            np.asarray(goal_xy, dtype=float),
            float(prog),
        )
        out.append((float(val), [float(g) for g in np.asarray(grad).reshape(-1)]))
    return out


